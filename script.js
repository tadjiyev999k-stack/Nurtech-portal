function getSingleTypeRelativeTime(timestamp) {
  const elapsedSecs = Math.floor((Date.now() - timestamp) / 1000);
  if (elapsedSecs < 60) return "hozirgina";
  const mins = Math.floor(elapsedSecs / 60);
  if (mins < 60) return `${mins} daqiqa oldin`;
  const hours = Math.floor(elapsedSecs / 3600);
  if (hours < 24) return `${hours} soat oldin`;
  const days = Math.floor(elapsedSecs / 86400);
  if (days < 30) return `${days} kun oldin`;
  const months = Math.floor(days / 30);
  if (months < 12) return `${months} oy oldin`;
  const years = Math.floor(days / 365);
  return `${years} yil oldin`;
}

