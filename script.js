function linkifyText(inputText) {
  let replacedText, replacePattern1, replacePattern2;
  replacePattern1 =
    /( (https?|ftp):\/\/[-A-Z0-9+&@#\/%?=~_|!:,.;]*[-A-Z0-9+&@#\/%=~_|])/gim;
  replacedText = inputText.replace(
    replacePattern1,
    '<a href="$1" target="_blank" style="color:var(--primary); text-decoration:underline;">$1</a>',
  );
  replacePattern2 = /(^|[^\/])(www\.[\S]+( |$))/gim;
  replacedText = replacedText.replace(
    replacePattern2,
    '$1<a href="http://$2" target="_blank" style="color:var(--primary); text-decoration:underline;">$2</a>',
  );
  return replacedText;
}

function renderFaculty(query) {
  const container = document.getElementById("faculty-grid");
  if (!container) return;
  container.innerHTML = "";

  let filtered = facultyMembers;
  if (query.trim() !== "") {
    const q = query.toLowerCase();
    filtered = filtered.filter((p) => {
      const translatedRole = getTranslatedRole(p.role).toLowerCase();
      return (
        p.name.toLowerCase().includes(q) ||
        p.role.toLowerCase().includes(q) ||
        translatedRole.includes(q)
      );
    });
  }

  const maxPages = Math.ceil(filtered.length / facultyPerPage) || 1;
  if (facultyCurrentPage >= maxPages) facultyCurrentPage = maxPages - 1;
  if (facultyCurrentPage < 0) facultyCurrentPage = 0;

  const startIdx = facultyCurrentPage * facultyPerPage;
  const pageItems = filtered.slice(startIdx, startIdx + facultyPerPage);

  const prevBtn = document.getElementById("faculty-prev");
  const nextBtn = document.getElementById("faculty-next");
  if (prevBtn) {
    if (facultyCurrentPage === 0) prevBtn.classList.add("disabled");
    else prevBtn.classList.remove("disabled");
  }

  if (nextBtn) {
    if (facultyCurrentPage >= maxPages - 1) nextBtn.classList.add("disabled");
    else nextBtn.classList.remove("disabled");
  }

  const indicator = document.getElementById("faculty-pagination-indicator");
  if (indicator) {
    indicator.textContent = `Sahifa ${facultyCurrentPage + 1} / ${maxPages} (Jami: ${filtered.length} xodim)`;
  }

  if (pageItems.length === 0) {
    container.innerHTML = `<p style="grid-column: 1/-1; text-align:center; color:var(--text-muted);">Xodimlar topilmadi.</p>`;
    return;
  }

  pageItems.forEach((person) => {
    const displayRole = getTranslatedRole(person.role);
    const card = document.createElement("div");
    card.className = "card faculty-card-item";
    card.innerHTML = `
      <div style="display:flex; gap:0.75rem; align-items:center;">
        <div style="width:2.5rem; height:2.5rem; min-width:2.5rem; border-radius:50%; background:var(--primary); color:#fff; display:flex; align-items:center; justify-content:center; font-weight:bold; font-size:1rem;">
          ${person.name.charAt(0)}
        </div>
        <div>
          <h3 class="card-title" style="font-size:0.9rem; margin:0; line-height:1.2;">${person.name}</h3>
          <p class="card-desc" style="font-size:0.75rem; margin:0.1rem 0 0; color:var(--primary); font-weight:600;">${displayRole}</p>
        </div>
      </div>
    `;
    container.appendChild(card);
  });
}

function getTranslatedRole(roleUz) {
  if (currentLang === "uz") return roleUz;
  if (roleTranslations[roleUz] && roleTranslations[roleUz][currentLang]) {
    return roleTranslations[roleUz][currentLang];
  }
  return roleUz;
}

function initCounterAnimation() {
  const counters = document.querySelectorAll(".stat-num");
  counters.forEach((counter) => {
    const target = +counter.getAttribute("data-target");
    let count = 0;
    const speed = target / 40;
    const updateCount = () => {
      count += speed;
      if (count < target) {
        if (target === 40) {
          counter.innerText = "+" + Math.ceil(count);
        } else if (counter.id === "stat-num-employment") {
          counter.innerText = Math.ceil(count) + "%";
        } else {
          counter.innerText = Math.ceil(count);
        }
        setTimeout(updateCount, 25);
      } else {
        if (target === 40) {
          counter.innerText = "+" + target;
        } else if (counter.id === "stat-num-employment") {
          counter.innerText = target + "%";
        } else {
          counter.innerText = target;
        }
      }
    };
    updateCount();
  });
}