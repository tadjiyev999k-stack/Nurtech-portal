function countAllCommentsAndReplies(arr) {
  if (!arr || !arr.length) return 0;
  let count = arr.length;
  arr.forEach((c) => {
    if (c.replies && c.replies.length > 0) {
      count += countAllCommentsAndReplies(c.replies);
    }
  });
  return count;
}

