function findCommentRecursive(commentsArray, targetId) {
  for (let c of commentsArray) {
    if (c.id === targetId) return c;
    if (c.replies && c.replies.length > 0) {
      let found = findCommentRecursive(c.replies, targetId);
      if (found) return found;
    }
  }
  return null;
}

