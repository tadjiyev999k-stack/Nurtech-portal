async function handleNewPost(e) {
  e.preventDefault();
  if (!currentUser) return;

  const editId = document.getElementById("edit-post-id").value;
  const type = document.getElementById("post-type").value;
  const rawTitle = document.getElementById("post-title").value.trim();
  const rawText = document.getElementById("post-text").value.trim();
  const deadline = document.getElementById("post-deadline").value;
  const allowEnroll = document.getElementById("post-allow-enroll").checked;

  // Enforce Min 10 Words Constraint
  const wordsCount = rawText ? rawText.split(/\s+/).length : 0;
  if (wordsCount < 10) {
    alert(
      `E'lon mazmuni kamida 10 ta so'zdan iborat bo'lishi lozim! Hozirgi so'zlar soni: ${wordsCount}`,
    );
    return;
  }

  if (editId) {
    // 1. IF EDITING: Update the existing row in Supabase cloud
    const { error } = await supabaseClient
      .from('announcements')
      .update({
        title: rawTitle,
        text: rawText,
        type: type
      })
      .eq('id', editId);

    if (error) {
      alert("Error updating announcement: " + error.message);
      return;
    }
  } else {
    // 2. IF CREATING NEW: Insert a new row into Supabase cloud
    const { error } = await supabaseClient
      .from('announcements')
      .insert([
        {
          title: rawTitle,
          text: rawText,
          type: type,
          author: `${currentUser.firstName} ${currentUser.lastName}`,
          author_email: currentUser.email
        }
      ]);

    if (error) {
      alert("Error saving announcement to cloud: " + error.message);
      return;
    }
  }

  // Close the popup modal and clear the form fields
  document.getElementById("post-modal").classList.remove("open");
  document.getElementById("post-form").reset();

  // Refresh the list from Supabase cloud
  await fetchAnnouncementsFromSupabase();
}

function readFileAsDataURL(file) {
  return new Promise((resolve) => {
    const reader = new FileReader();
    reader.onload = (e) => resolve(e.target.result);
    reader.readAsDataURL(file);
  });
}

async function deleteAnnouncement(postId) {
  const { error } = await supabaseClient
    .from('announcements')
    .delete()
    .eq('id', postId);

  if (error) {
    alert("Error deleting announcement: " + error.message);
    return;
  }

  // Refresh the list from Supabase cloud
  await fetchAnnouncementsFromSupabase();
  // Update profile modal list if open
  if (document.getElementById("profile-modal").classList.contains("open")) {
    renderMyPostsList();
  }
}

